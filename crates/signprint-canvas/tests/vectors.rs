//! PRNG output and known-answer pattern hashes, shared with the browser client.
//!
//! Regenerate with `SIGNPRINT_BLESS=1 cargo test -p signprint-canvas --test vectors`.

use std::path::PathBuf;

use serde_json::json;
use signprint_canvas::{pattern, prng::Rng};

fn generate() -> serde_json::Value {
    let prng: Vec<_> = [0u32, 1, 0xdead_beef, u32::MAX]
        .iter()
        .map(|seed| {
            let mut r = Rng::new(*seed);
            json!({ "seed": seed, "first": (0..8).map(|_| r.next_u32()).collect::<Vec<_>>() })
        })
        .collect();
    let patterns: Vec<_> = [1u32, 2, 3, 0x1234_5678, 4_000_000_000]
        .iter()
        .map(|seed| {
            let (bg, rects) = pattern::layout(*seed);
            json!({
                "seed": seed,
                "background": bg,
                "rects": rects.iter().map(|r| json!([r.x, r.y, r.w, r.h, r.rgb])).collect::<Vec<_>>(),
                "hash": pattern::expected_hash(*seed),
            })
        })
        .collect();
    json!({
        "comment": "generated by crates/signprint-canvas/tests/vectors.rs, do not edit",
        "pattern_size": [pattern::WIDTH, pattern::HEIGHT],
        "prng": prng,
        "patterns": patterns,
    })
}

#[test]
fn canvas_vectors_are_current() {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../testvectors/canvas.json");
    let fresh = serde_json::to_string_pretty(&generate()).unwrap() + "\n";
    if std::env::var_os("SIGNPRINT_BLESS").is_some() {
        std::fs::write(&path, &fresh).unwrap();
        return;
    }
    let on_disk = std::fs::read_to_string(&path)
        .expect("testvectors/canvas.json missing; run with SIGNPRINT_BLESS=1")
        .replace("\r\n", "\n");
    assert!(
        on_disk == fresh,
        "testvectors/canvas.json is stale; rerun with SIGNPRINT_BLESS=1"
    );
}
