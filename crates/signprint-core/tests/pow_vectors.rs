//! Argon2id puzzle vectors shared with the browser client: the same inputs
//! must hash identically in RustCrypto's argon2 and the client's WASM build,
//! and the first solving nonces must agree.
//!
//! Regenerate with `SIGNPRINT_BLESS=1 cargo test -p signprint-core --test pow_vectors`.

use std::path::PathBuf;

use serde_json::json;
use signprint_core::pow::{self, PowParams};
use signprint_wire::b64;

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

fn generate() -> serde_json::Value {
    let params = PowParams {
        memory_kib: 64,
        iterations: 1,
        puzzles: 3,
        bits: 4,
    };
    let id = [0x5au8; 16];
    let hashes: Vec<_> = [(0u8, 0u32), (0, 1), (1, 12345), (2, u32::MAX)]
        .iter()
        .map(|(i, n)| {
            json!({
                "index": i,
                "nonce": n,
                "hash_hex": hex(&pow::hash(&params, &id, *i, *n).unwrap()),
            })
        })
        .collect();
    json!({
        "comment": "generated by crates/signprint-core/tests/pow_vectors.rs, do not edit",
        "params": { "memory_kib": params.memory_kib, "iterations": params.iterations, "puzzles": params.puzzles, "bits": params.bits },
        "id": b64::encode_url(&id),
        "hashes": hashes,
        "solution": pow::solve(&params, &id),
    })
}

#[test]
fn pow_vectors_are_current() {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../testvectors/pow.json");
    let fresh = serde_json::to_string_pretty(&generate()).unwrap() + "\n";
    if std::env::var_os("SIGNPRINT_BLESS").is_some() {
        std::fs::write(&path, &fresh).unwrap();
        return;
    }
    let on_disk = std::fs::read_to_string(&path)
        .expect("testvectors/pow.json missing; run with SIGNPRINT_BLESS=1")
        .replace("\r\n", "\n");
    assert!(on_disk == fresh, "testvectors/pow.json is stale; rerun with SIGNPRINT_BLESS=1");
}
