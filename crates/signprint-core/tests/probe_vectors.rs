//! Writes sample probe programs and their expected answers to
//! testvectors/probe.json. The client's browser tests run each program in
//! real engines and check they arrive at the same number we compute here.
//!
//! Regenerate with `SIGNPRINT_BLESS=1 cargo test -p signprint-core --test probe_vectors`.

use std::path::PathBuf;

use serde_json::json;
use signprint_core::probe;

fn generate() -> serde_json::Value {
    let cases: Vec<_> = [1u64, 2, 0xdead_beef, u64::MAX, 1_760_716_800]
        .iter()
        .enumerate()
        .map(|(i, seed)| {
            let id = [i as u8 + 1; 16];
            let p = probe::generate(*seed, &id);
            json!({
                "seed": seed.to_string(),
                "registry_key": probe::registry_key(&id),
                "source": p.source,
                "field": p.field,
                "answer": p.answer,
            })
        })
        .collect();
    json!({
        "comment": "generated by crates/signprint-core/tests/probe_vectors.rs, do not edit",
        "programs": cases,
    })
}

#[test]
fn probe_vectors_are_current() {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../testvectors/probe.json");
    let fresh = serde_json::to_string_pretty(&generate()).unwrap() + "\n";
    if std::env::var_os("SIGNPRINT_BLESS").is_some() {
        std::fs::write(&path, &fresh).unwrap();
        return;
    }
    let on_disk = std::fs::read_to_string(&path)
        .expect("testvectors/probe.json missing; run with SIGNPRINT_BLESS=1")
        .replace("\r\n", "\n");
    assert!(
        on_disk == fresh,
        "testvectors/probe.json is stale; rerun with SIGNPRINT_BLESS=1"
    );
}
